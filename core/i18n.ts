export const strings = (lang: Lang): Strings => (lang === 'zh' ? ZH : EN)

/** A refusal's detail in one short line: a known code translated, anything else cut to its first line. */
const shortDetail = (lang: Lang, detail: string) => {
  const known = strings(lang).reasons[detail]
  if (known !== undefined) return known
  const line = detail.replace(/<\/?tool_use_error>/g, '').trim().split('\n')[0] ?? ''
  return line.length > 120 ? `${line.slice(0, 120)}…` : line
}

export const noteText = (lang: Lang, note: Note): string => {
  const s = strings(lang).notes
  return note.code === 'spawn-refused' ? s['spawn-refused'](note.detail !== undefined ? shortDetail(lang, note.detail) : undefined) : s[note.code]
}

/** Words a stored error (`reason` or `reason: detail`); unknown parts stay as they are. */
export const errorText = (lang: Lang, error: string): string => {
  const reasons = strings(lang).reasons
  const at = error.indexOf(': ')
  const [head, tail] = at === -1 ? [error, ''] : [error.slice(0, at), error.slice(at + 2)]
  const word = (part: string) => reasons[part] ?? part
  return tail === '' ? word(head) : `${word(head)}: ${word(tail)}`
}
